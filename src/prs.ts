import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import type { Config } from './config.js';
import type { RepoResult } from './sync.js';

export interface PrPlan { repo: string; branch: string; title: string; commitMessage: string; body: string; commands: string[] }

export function planPr(config: Config, r: RepoResult): PrPlan {
  const ref = config.template.ref;
  const short = ref.length === 40 ? ref.slice(0, 7) : ref;
  const changed = r.files.filter((f) => f.status !== 'in-sync');
  const branch = `chore/rules-sync-${short}`.replace(/[^\w./-]/g, '-');
  const title = `chore(rules): sync shared rules from template ${short}`.slice(0, 72);
  const list = changed.map((f) => `- ${f.status}: \`${f.file}\``).join('\n');
  const commitMessage = `${title}\n\nUpdate shared text from ${config.template.repo}@${short} and keep\nREPO-SPECIFIC blocks unchanged.\n\nRefs: none\nAgent: rules-sync`;
  const body = `## Summary

Sync ${changed.length} shared file(s) with ${config.template.repo}@${short} (${config.template.path}). REPO-SPECIFIC blocks are kept from this repo.

${list}

Tracking: none

## Validation

- pass: \`rules-sync check\` reported the drift listed above
- not_run: this repo's own tests, CI runs them on this PR

## Size

<!-- Paste the output line of \`node scripts/check/pr-size.mjs\`. -->

## Review checklist

- [ ] Scope matches the task spec; follow-ups are listed, not done.
- [ ] Every acceptance criterion has a test or a recorded check.
- [ ] Docs that describe the changed behavior are updated.
- [ ] No secrets, \`.env*\`, personal paths or raw transcripts are in the diff.
- [ ] No new dependency, CI change or auth/billing change without owner approval.
- [ ] Nothing left running; my worktree will be removed after merge.

## Risks and follow-ups

Template changes may need repo-specific follow-ups. Generated by rules-sync.
`;
  const commands = [
    `gh repo clone ${r.target.repo} <workdir> -- --depth 1`,
    `git -C <workdir> switch -c ${branch}`,
    `# write ${changed.length} file(s) under <workdir>/${r.target.path ?? ''}`,
    `git -C <workdir> add -A`,
    `git -C <workdir> commit -F <commit-message-file>`,
    `git -C <workdir> push -u origin ${branch}`,
    `gh pr create --repo ${r.target.repo} --head ${branch} --title "${title}" --body-file <body-file>`,
  ];
  return { repo: r.target.repo, branch, title, commitMessage, body, commands };
}

/** Only called with --yes: clone fresh, branch, commit, push and open the PR. Never merges. */
export function applyPr(p: PrPlan, r: RepoResult): string {
  const work = mkdtempSync(join(tmpdir(), 'rules-sync-pr-'));
  const run = (cmd: string, args: string[], cwd?: string) => execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
  const wd = join(work, 'repo');
  run('gh', ['repo', 'clone', r.target.repo, wd, '--', '--depth', '1']);
  run('git', ['switch', '-c', p.branch], wd);
  for (const f of r.files.filter((x) => x.status !== 'in-sync')) {
    const dest = join(wd, r.target.path ?? '', f.file);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, f.desired);
    if (f.file.startsWith('.githooks/')) chmodSync(dest, 0o755);
  }
  run('git', ['add', '-A'], wd);
  writeFileSync(join(work, 'msg'), p.commitMessage);
  writeFileSync(join(work, 'body'), p.body);
  run('git', ['commit', '-q', '-F', join(work, 'msg')], wd);
  run('git', ['push', '-q', '-u', 'origin', p.branch], wd);
  return run('gh', ['pr', 'create', '--repo', r.target.repo, '--head', p.branch, '--title', p.title, '--body-file', join(work, 'body')], wd).trim();
}
